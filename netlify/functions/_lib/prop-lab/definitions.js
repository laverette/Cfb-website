function getPropDef(id) {
  return PROP_BY_ID[String(id || "")] || null;
}

function catalogPublic() {
  return PROP_DEFINITIONS.map((d) => ({
    id: d.id,
    label: d.label,
    short: d.short,
    category: d.category,
    family: d.family,
    combo: Boolean(d.combo),
  }));
}

